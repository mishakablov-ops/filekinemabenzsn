import type { StyleId } from "../theme/styles";

/**
 * Anchor = when something happens.
 *  number            seconds (absolute for scenes, relative to scene start for layers/events)
 *  "3.2s" | "3.2"    same as number
 *  "@слово"          start of the next spoken occurrence of the word/phrase (search starts at the scene start)
 *  "@слово>"         end of that word/phrase
 *  "@слово#2"        2nd occurrence
 *  "@слово+0.2"      offset in seconds (also "-0.1"), combinable: "@за первую неделю>+0.1"
 *  "card:4"          start of caption card 4 (0-based)
 *  "beat:16" "bar:8" "drop:1"   music grid (promo mode)
 *  "end"             end of the composition (or of the scene for layers)
 *  "f:120"           absolute frame
 */
export type Anchor = number | string;

export type PosPreset =
  | "full" | "stage" | "stageHigh" | "stageLow" | "center" | "top" | "upper" | "lower" | "bottom"
  | "left" | "right" | "topLeft" | "topRight" | "bottomLeft" | "bottomRight";

export type Pos =
  | PosPreset
  | { x?: number; y?: number; w?: number; h?: number; preset?: PosPreset; dx?: number; dy?: number; scale?: number; rotate?: number };

export type LayerSpec = {
  block: string;
  props?: Record<string, unknown>;
  at?: Anchor;
  until?: Anchor;
  pos?: Pos;
  enter?: string;
  exit?: string;
  z?: number;
  sfx?: string | false;
  /** parallax depth for camera moves: 0 = locked to camera, 1 = full move */
  depth?: number;
  /** intentional overlap (badge on a card, cursor over UI): QA won't flag it */
  overlap?: boolean;
  /** bg only: darken the background (0–1) from `dimAt` (anchor; default scene start) so a hero layer pops */
  dim?: number;
  dimAt?: Anchor;
};

export type CameraSpec = {
  move?: string; // push | pull | drift | panUp | panDown | panLeft | panRight | tilt | orbit | still | punch
  amount?: number;
  shakeAt?: Anchor[];
  focusFrom?: number; // starts blurred (px) and racks focus
};

export type TransitionSpec = { type: string; dur?: number; sfx?: string | false };

export type CaptionMode = "editorial" | "subtitle" | "slam" | "stack" | "karaoke" | "vhs" | "none";
export type CaptionPos = "top" | "upper" | "middle" | "lower" | "bottom";

export type CaptionsSpec = {
  mode?: CaptionMode;
  pos?: CaptionPos;
  tone?: "dark" | "light"; // text colour family (light text on dark bg = "light")
  scale?: number;
  shadow?: boolean;
  align?: "center" | "left";
  uppercase?: boolean;
  /** legibility gradient behind the caption band: true/0..1, auto-on for 3D / photo / video backgrounds; false disables */
  scrim?: boolean | number;
};

export type SceneSpec = {
  id?: string;
  at: Anchor;
  until?: Anchor;
  bg?: LayerSpec | string;
  camera?: CameraSpec | string;
  transition?: TransitionSpec | string;
  captions?: CaptionsSpec | false;
  layers?: LayerSpec[];
  /** style override for this scene only */
  style?: StyleId;
};

/** id = a library sound; or src = a file inside the project (from/dur seconds into it, fade-out at the end) */
export type SfxCue = { at: Anchor; id: string; volume?: number; alignPeak?: boolean; src?: string; from?: number; dur?: number; fade?: number };

export type Spec = {
  id: string;
  mode?: "explainer" | "promo";
  style: StyleId;
  fps?: number;
  width?: number;
  height?: number;
  duration?: number;
  tail?: number;
  voice?: { src: string; words?: string; volume?: number };
  music?: { src: string; volume?: number; duck?: number; beats?: string; offset?: number; fadeIn?: number; fadeOut?: number };
  captions?: CaptionsSpec;
  scenes: SceneSpec[];
  sfx?: SfxCue[];
  autoSfx?: boolean;
  sfxVolume?: number;
  grain?: number;
  vignette?: number;
  /** words/cards without voice (promo): generated by tts.py --silent */
  words?: string;
};

export type WordStyle = "italic" | "accent" | "mark" | "strike" | "alt" | "big" | "outline" | "neg" | "pos";

export type Word = {
  i: number;
  text: string; // display text (may contain nbsp)
  start: number;
  end: number;
  card: number;
  role: "lead" | "punch";
  style?: WordStyle[];
  line?: number; // explicit line index inside role (from "/" markup)
};

export type Card = {
  i: number;
  start: number;
  end: number;
  words: number[];
  mode?: CaptionMode;
  pos?: CaptionPos;
};

export type Transcript = { words: Word[]; cards: Card[]; duration: number; text?: string };

export type BeatGrid = {
  bpm: number;
  beatSec: number;
  barSec: number;
  beats: number[];
  bars: number[];
  sections: { name: string; start: number; end: number; energy: number }[];
  drops: number[];
  duration: number;
};

export type ReelProps = {
  project: string;
  /** draw + log overlap / safe-zone problems (QA renders only) */
  qa?: boolean;
  /** render-time fps override (previews at 30) */
  fps?: number;
  spec?: Spec;
  transcript?: Transcript | null;
  beats?: BeatGrid | null;
  sfxIndex?: SfxMeta[];
};

export type SfxMeta = {
  id: string; file?: string; category: string; desc: string; tags: string[]; dur: number; peak: number;
  /** plays another sound instead (null = silent) — retired synthetic sounds and ids mapped onto an imported pack */
  alias?: string | null;
  source?: "gen" | "pack";
};
