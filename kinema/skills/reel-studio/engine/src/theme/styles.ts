import { F } from "../fonts";
import type { CaptionMode, CaptionPos } from "../core/types";

export type StyleId =
  | "dusk" | "ember" | "sand" | "blaze" | "cloud" | "night" | "cinema" | "studio" | "space" | "paper" | "brutal" | "neon" | "terminal" | "pop";

export type Theme = {
  id: StyleId;
  dark: boolean;
  // surfaces
  bg: string; // css background for default bg block
  bgBlock: string; // default background block id
  bgProps?: Record<string, unknown>;
  // text
  ink: string; // primary text
  muted: string; // lead line / secondary
  faint: string;
  accent: string; // main accent (blue / orange / acid)
  accent2: string; // secondary accent
  neg: string; // red, problems
  pos: string; // green, success
  markBg: string; // highlight box behind words
  markInk: string;
  // cards / UI chrome
  card: string;
  cardInk: string;
  cardMuted: string;
  cardBorder: string;
  cardShadow: string;
  glass: string;
  radius: number;
  // type
  fontDisplay: string;
  fontSerif: string;
  fontUi: string;
  fontMono: string;
  displayWeight: number;
  displayTracking: string; // letter-spacing for big type
  serifWeight: number;
  uppercase: boolean;
  // captions
  captionMode: CaptionMode;
  captionPos: CaptionPos;
  captionShadow: string; // text-shadow for legibility on footage
  captionScale: number;
  // motion
  motion: {
    enter: string; // default layer entrance
    transition: string; // default scene transition
    transDur: number; // seconds
    camera: string; // default camera move
    energy: number; // 0..1 how punchy (shake, overshoot, cut speed)
  };
  grain: number;
  vignette: number;
};

